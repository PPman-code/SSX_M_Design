import { test, expect } from '@playwright/test';

test('course preview toggles remaining seats and supports separate seats for multiple classes', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.goto('/#/?page=parent-course-detail&theme=light');
  const panel = page.getByRole('region', { name: '页面配置', exact: true });
  const multiple = panel.getByRole('switch', { name: '班级多选', exact: true });
  const remaining = panel.getByRole('switch', { name: '剩余席位', exact: true });
  await expect(multiple).not.toBeChecked(); await expect(remaining).toBeChecked();
  const frame = page.frameLocator('iframe');
  const row = frame.getByRole('button', { name: '选择少儿声乐启蒙课规格参数', exact: true });
  await row.click();
  const specs = frame.getByRole('dialog', { name: '选择规格参数', exact: true });
  const seats = frame.getByRole('dialog', { name: '选择座位', exact: true });
  await specs.getByRole('button', { name: '20课时', exact: true }).click();
  await expect(specs.locator('.parent-class-quota')).toHaveCount(3);
  await remaining.click();
  await expect(specs.locator('.parent-class-quota')).toHaveCount(0);
  await expect(specs.getByRole('button', { name: '20课时', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(specs.getByRole('button', { name: /声乐启蒙·周日上午班/ })).toBeDisabled();
  await remaining.click(); await expect(specs.locator('.parent-class-quota')).toHaveCount(3);
  await multiple.click();
  await expect(specs.locator('.parent-class-section h3')).toHaveText('选择班级 必选');
  await expect(specs.locator('.parent-class-section h3')).toHaveText('选择班级 可多选');
  const first = specs.locator('[data-class-id="class-1"]');
  const third = specs.locator('[data-class-id="class-3"]');
  await first.locator('.parent-class-choice').click(); await third.locator('.parent-class-choice').click();
  await expect(specs.locator('.parent-class-card.is-selected')).toHaveCount(2);
  await first.getByRole('button', { name: '选择座位', exact: true }).click();
  await expect(seats.locator('.parent-selection-course')).toHaveText('声乐启蒙·周六基础班');
  await seats.getByRole('button', { name: '1排2座', exact: true }).click();
  await seats.getByRole('button', { name: '确定', exact: true }).click();
  await specs.getByRole('button', { name: '确定', exact: true }).click();
  await expect(frame.locator('.toast-message')).toHaveText('请为“声乐启蒙·周六提高班”选择座位');
  await third.getByRole('button', { name: '选择座位', exact: true }).click();
  await expect(seats.locator('.parent-selection-course')).toHaveText('声乐启蒙·周六提高班');
  await seats.getByRole('button', { name: '3排3座', exact: true }).click();
  await seats.getByRole('button', { name: '确定', exact: true }).click();
  await expect(first).toContainText('座位 1排2座'); await expect(third).toContainText('座位 3排3座');
  await page.screenshot({ path: 'outputs/parent-course-config-multiple.png' });
  await specs.getByRole('button', { name: '确定', exact: true }).click();
  await expect(row).toContainText('声乐启蒙·周六基础班'); await expect(row).toContainText('声乐启蒙·周六提高班');
  await expect(row).toContainText('1-2'); await expect(row).toContainText('3-3');
  await row.click(); await first.locator('.parent-class-choice').click();
  await expect(specs.locator('.parent-class-card.is-selected')).toHaveCount(1);
  await specs.getByRole('button', { name: '关闭弹层', exact: true }).click();
  await row.click(); await expect(specs.locator('.parent-class-card.is-selected')).toHaveCount(2);
  await multiple.click();
  await expect(specs.locator('.parent-class-section h3')).toHaveText('选择班级 必选');
  await expect(specs.locator('.parent-class-card.is-selected')).toHaveCount(1);
  await expect(first).toContainText('座位 1排2座');
  await specs.getByRole('button', { name: '确定', exact: true }).click();
  await expect(row).toContainText('声乐启蒙·周六基础班'); await expect(row).not.toContainText('声乐启蒙·周六提高班');
});

test('direct course URL supports multiple classes without seats and hidden remaining counts', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/#/pages/parent-course-detail/v1?theme=dark&classMultiple=enabled&remainingSeats=hidden');
  const row = page.getByRole('button', { name: '选择音乐律动与舞台表现课（含练习道具）规格参数', exact: true });
  await row.click();
  const specs = page.getByRole('dialog', { name: '选择规格参数', exact: true });
  await expect(specs.locator('.parent-class-quota')).toHaveCount(0);
  await specs.getByRole('button', { name: /舞台表现·周六基础班/ }).click();
  await specs.getByRole('button', { name: /舞台表现·周六提高班/ }).click();
  await specs.getByRole('button', { name: /节奏练习沙锤/ }).click();
  await expect(specs.locator('.parent-class-seat')).toHaveCount(0);
  await specs.getByRole('button', { name: '确定', exact: true }).click();
  await expect(row).toContainText('舞台表现·周六基础班'); await expect(row).toContainText('舞台表现·周六提高班');
  await expect(row).toContainText('节奏练习沙锤');
});
